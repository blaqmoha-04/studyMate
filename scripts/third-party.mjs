// Generates docs/THIRD_PARTY.md from package-lock.json (production dependencies only) and flags non-permissive licences.
//   npm run licenses
import fs from 'node:fs';
const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const PERMISSIVE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'BlueOak-1.0.0', 'Unlicense', 'CC0-1.0', 'Python-2.0', 'MIT-0']);
const rows = [];
for (const [key, p] of Object.entries(lock.packages)) {
  if (!key || p.dev) continue;
  const name = key.split('node_modules/').pop();
  let license = p.license ?? null;
  if (!license) { try { license = JSON.parse(fs.readFileSync(`${key}/package.json`, 'utf8')).license ?? 'UNKNOWN'; } catch { license = 'UNKNOWN'; } }
  if (typeof license === 'object') license = license.type ?? 'UNKNOWN';
  rows.push({ name, version: p.version, license });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const flagged = rows.filter((r) => !r.license.split(/\s+(?:OR|AND)\s+|[()]/).filter(Boolean).some((l) => PERMISSIVE.has(l.trim())));
const counts = {}; for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1;
const md = `# Third-party software, fonts and images

_Generated by \`npm run licenses\` from package-lock.json on ${new Date().toISOString().slice(0, 10)}. Re-run it whenever dependencies change._

## What the browser loads
- **No third-party scripts, stylesheets, fonts, images, trackers or SDKs.** Everything is served from your own server. An automated test (\`server/tests/frontend.test.js\`) fails if any client file references an external URL, and the Content-Security-Policy (\`default-src 'self'\`) blocks anything else.
- **Fonts:** the system font stack only (\`system-ui, Segoe UI, Roboto, …\`). No font files are bundled or downloaded, so there is nothing to license.
- **Images:** none, apart from \`client/assets/favicon.svg\`, drawn for this project.
- **Icons:** the small outline icons in \`client/js/dom.js\` are simple geometric paths written for this project (no icon library is included).

## Server runtime dependencies that ship in the Docker image (direct)
| Package | Used for |
|---|---|
| express | web framework |
| pg | PostgreSQL driver |
| argon2 | password hashing |
| helmet | security headers |
| express-rate-limit | rate limiting |
| zod | input validation |
| cookie-parser | reading the session cookie |
| pino, pino-http | structured logging |
| nodemailer | optional SMTP email (password-reset links) |

## Container images and external services (operator-chosen)
| Item | Licence / note |
|---|---|
| postgres:16-alpine | PostgreSQL Licence (permissive) |
| nginx:1.27-alpine | BSD-2-Clause |
| node:22-bookworm-slim | MIT (Node.js) plus Debian packages under their own licences |
| certbot/certbot | Apache-2.0; talks to Let's Encrypt (receives your domain and the contact email you give it) |
| SMTP provider (optional) | Whichever provider you configure in \`SMTP_URL\`; it will see recipients' email addresses. List it in \`OPERATOR_PROCESSORS\` so the Privacy Policy names it. |

## All production npm packages (${rows.length}) by licence
${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`).join('\n')}

**Packages whose licence is not on the permissive allow-list (${PERMISSIVE.size} licences): ${flagged.length ? '' : 'none'}**
${flagged.map((r) => `- ${r.name}@${r.version}: ${r.license}`).join('\n')}

<details><summary>Full list</summary>

| Package | Version | Licence |
|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')}

</details>

Development-only packages (test tools such as supertest, jsdom, yaml) are not shipped in the production image.
`;
fs.writeFileSync('docs/THIRD_PARTY.md', md);
console.log(`${rows.length} production packages; licences:`, counts, flagged.length ? `NOT ALLOW-LISTED: ${flagged.map((r) => `${r.name}(${r.license})`).join(', ')}` : 'all permissive');
